CREATE TABLE auditoria (
	id INTEGER NOT NULL, 
	usuario_codigo VARCHAR(20), 
	usuario_nome VARCHAR(180) NOT NULL, 
	modulo VARCHAR(80) NOT NULL, 
	acao VARCHAR(80) NOT NULL, 
	entidade VARCHAR(80), 
	registro_referencia VARCHAR(120), 
	detalhes TEXT, 
	dados_anteriores TEXT, 
	dados_novos TEXT, 
	criado_em DATETIME NOT NULL, 
	PRIMARY KEY (id)
);
CREATE TABLE clientes (
	codigo VARCHAR(20) NOT NULL, 
	nome VARCHAR(180) NOT NULL, 
	tipo VARCHAR(30) NOT NULL, 
	documento VARCHAR(14) NOT NULL, 
	telefone VARCHAR(30), 
	email VARCHAR(160), 
	cep VARCHAR(8), 
	logradouro VARCHAR(180) NOT NULL, 
	numero VARCHAR(20), 
	complemento VARCHAR(100), 
	bairro VARCHAR(120), 
	cidade VARCHAR(120) NOT NULL, 
	uf VARCHAR(2) NOT NULL, 
	status VARCHAR(20) NOT NULL, 
	criado_em DATETIME NOT NULL, 
	atualizado_em DATETIME NOT NULL, 
	PRIMARY KEY (codigo), 
	CONSTRAINT ck_cliente_tipo_valido CHECK (tipo IN ('pessoa_fisica', 'pessoa_juridica')), 
	CONSTRAINT ck_cliente_status_valido CHECK (status IN ('ativo', 'inativo'))
);
CREATE TABLE credenciais_usuarios (
	usuario_codigo VARCHAR(20) NOT NULL, 
	senha_hash VARCHAR(128) NOT NULL, 
	senha_salt VARCHAR(128) NOT NULL, 
	atualizado_em DATETIME NOT NULL, 
	PRIMARY KEY (usuario_codigo)
);
CREATE TABLE fornecedores (
	codigo VARCHAR(20) NOT NULL, 
	razao_social VARCHAR(180) NOT NULL, 
	nome_fantasia VARCHAR(150), 
	cnpj VARCHAR(14) NOT NULL, 
	categoria VARCHAR(80) NOT NULL, 
	contato VARCHAR(120), 
	telefone VARCHAR(30), 
	email VARCHAR(160), 
	cidade VARCHAR(120) NOT NULL, 
	uf VARCHAR(2) NOT NULL, 
	prazo_medio_entrega INTEGER NOT NULL, 
	status VARCHAR(20) NOT NULL, 
	criado_em DATETIME NOT NULL, 
	atualizado_em DATETIME NOT NULL, 
	PRIMARY KEY (codigo), 
	CONSTRAINT ck_fornecedor_prazo_nao_negativo CHECK (prazo_medio_entrega >= 0), 
	CONSTRAINT ck_fornecedor_status_valido CHECK (status IN ('ativo', 'inativo'))
);
CREATE TABLE itens_pedido (
	id INTEGER NOT NULL, 
	pedido_codigo VARCHAR(20) NOT NULL, 
	produto_sku VARCHAR(20) NOT NULL, 
	produto_nome VARCHAR(150) NOT NULL, 
	quantidade INTEGER NOT NULL, 
	valor_unitario NUMERIC(12, 2) NOT NULL, 
	subtotal NUMERIC(12, 2) NOT NULL, 
	criado_em DATETIME NOT NULL, 
	PRIMARY KEY (id), 
	CONSTRAINT ck_item_pedido_quantidade_positiva CHECK (quantidade > 0), 
	CONSTRAINT ck_item_pedido_valor_unitario_nao_negativo CHECK (valor_unitario >= 0), 
	CONSTRAINT ck_item_pedido_subtotal_nao_negativo CHECK (subtotal >= 0), 
	FOREIGN KEY(pedido_codigo) REFERENCES pedidos (codigo) ON DELETE CASCADE
);
CREATE TABLE movimentacoes (
	id INTEGER NOT NULL, 
	produto_sku VARCHAR(20) NOT NULL, 
	produto_nome VARCHAR(150) NOT NULL, 
	tipo VARCHAR(20) NOT NULL, 
	quantidade INTEGER NOT NULL, 
	origem VARCHAR(200) NOT NULL, 
	destino VARCHAR(200) NOT NULL, 
	saldo_anterior INTEGER NOT NULL, 
	saldo_posterior INTEGER NOT NULL, 
	criado_em DATETIME NOT NULL, 
	PRIMARY KEY (id), 
	CONSTRAINT ck_movimentacao_quantidade_positiva CHECK (quantidade > 0), 
	CONSTRAINT ck_movimentacao_saldo_anterior_nao_negativo CHECK (saldo_anterior >= 0), 
	CONSTRAINT ck_movimentacao_saldo_posterior_nao_negativo CHECK (saldo_posterior >= 0), 
	CONSTRAINT ck_movimentacao_tipo_valido CHECK (tipo IN ('entrada', 'saida'))
);
CREATE TABLE pedidos (
	codigo VARCHAR(20) NOT NULL, 
	cliente_nome VARCHAR(150) NOT NULL, 
	destino VARCHAR(200) NOT NULL, 
	transportadora VARCHAR(120), 
	codigo_rastreio VARCHAR(80), 
	status VARCHAR(20) NOT NULL, 
	valor_total NUMERIC(12, 2) NOT NULL, 
	criado_em DATETIME NOT NULL, 
	atualizado_em DATETIME NOT NULL, 
	PRIMARY KEY (codigo), 
	CONSTRAINT ck_pedido_status_valido CHECK (status IN ('pendente', 'processando', 'enviado', 'entregue')), 
	CONSTRAINT ck_pedido_valor_total_nao_negativo CHECK (valor_total >= 0)
);
CREATE TABLE produtos (
	sku VARCHAR(20) NOT NULL, 
	nome VARCHAR(150) NOT NULL, 
	categoria VARCHAR(80) NOT NULL, 
	marca VARCHAR(100), 
	especificacao VARCHAR(180), 
	gtin_ean VARCHAR, 
	estoque_atual INTEGER NOT NULL, 
	estoque_minimo INTEGER NOT NULL, 
	custo_unitario NUMERIC(12, 2) NOT NULL, 
	margem_lucro_percentual NUMERIC(7, 4) NOT NULL, 
	ncm VARCHAR(8), 
	regime_tributario VARCHAR(30) NOT NULL, 
	uf_referencia VARCHAR(2) NOT NULL, 
	referencia_fiscal VARCHAR(40) NOT NULL, 
	aliquota_icms NUMERIC(7, 4) NOT NULL, 
	aliquota_pis NUMERIC(7, 4) NOT NULL, 
	aliquota_cofins NUMERIC(7, 4) NOT NULL, 
	aliquota_ipi NUMERIC(7, 4) NOT NULL, 
	aliquota_simples NUMERIC(7, 4) NOT NULL, 
	aliquota_cbs NUMERIC(7, 4) NOT NULL, 
	aliquota_ibs NUMERIC(7, 4) NOT NULL, 
	calculo_preco_automatico BOOLEAN NOT NULL, 
	preco_venda_manual NUMERIC(12, 2), 
	valor_margem NUMERIC(12, 2) NOT NULL, 
	base_comercial NUMERIC(12, 2) NOT NULL, 
	valor_icms NUMERIC(12, 2) NOT NULL, 
	valor_pis NUMERIC(12, 2) NOT NULL, 
	valor_cofins NUMERIC(12, 2) NOT NULL, 
	valor_ipi NUMERIC(12, 2) NOT NULL, 
	valor_simples NUMERIC(12, 2) NOT NULL, 
	valor_cbs NUMERIC(12, 2) NOT NULL, 
	valor_ibs NUMERIC(12, 2) NOT NULL, 
	preco_venda NUMERIC(12, 2) NOT NULL, 
	criado_em DATETIME NOT NULL, 
	atualizado_em DATETIME NOT NULL, 
	PRIMARY KEY (sku), 
	CONSTRAINT ck_produto_estoque_atual_nao_negativo CHECK (estoque_atual >= 0), 
	CONSTRAINT ck_produto_estoque_minimo_nao_negativo CHECK (estoque_minimo >= 0), 
	CONSTRAINT ck_produto_custo_unitario_nao_negativo CHECK (custo_unitario >= 0), 
	CONSTRAINT ck_produto_margem_nao_negativa CHECK (margem_lucro_percentual >= 0), 
	CONSTRAINT ck_produto_preco_venda_nao_negativo CHECK (preco_venda >= 0), 
	CONSTRAINT ck_produto_regime_tributario_valido CHECK (regime_tributario IN ('lucro_presumido', 'lucro_real', 'simples_nacional', 'manual'))
);
CREATE TABLE sessoes_usuarios (
	id INTEGER NOT NULL, 
	token_hash VARCHAR(64) NOT NULL, 
	usuario_codigo VARCHAR(20) NOT NULL, 
	criado_em DATETIME NOT NULL, 
	expira_em DATETIME NOT NULL, 
	revogado_em DATETIME, 
	PRIMARY KEY (id)
);
CREATE TABLE usuarios (
	codigo VARCHAR(20) NOT NULL, 
	nome VARCHAR(180) NOT NULL, 
	email VARCHAR(180) NOT NULL, 
	cargo VARCHAR(120) NOT NULL, 
	perfil VARCHAR(30) NOT NULL, 
	status VARCHAR(20) NOT NULL, 
	ultimo_acesso DATETIME, 
	criado_em DATETIME NOT NULL, 
	atualizado_em DATETIME NOT NULL, 
	PRIMARY KEY (codigo), 
	CONSTRAINT ck_usuario_perfil_valido CHECK (perfil IN ('administrador', 'gerente', 'operador', 'consulta')), 
	CONSTRAINT ck_usuario_status_valido CHECK (status IN ('ativo', 'inativo'))
);
